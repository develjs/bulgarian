function makeEmptyPageState(items) {
  return items.map((item) => ({
    values: item.blanks.map(() => ""),
    checked: false,
    result: null,
    comment: ""
  }));
}
function makeEmptyAllState() {
  return EXERCISES.map(ex => makeEmptyPageState(ex.items));
}

